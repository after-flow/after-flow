/*
  同意の項目の URL（Backend の同意の一覧が返す）と、本文の対応。
  外部のAI事業者への提供（/legal/cross-border-ai）は、いまは個人情報の取扱いの「4. 外部のAI事業者への提供」に書いている。
  専用の文書ができたら LEGAL_DOCS に足して、ここから外す
*/
const ALIASES: Record<string, string> = { 'cross-border-ai': 'privacy' }

/** '/legal/terms' や 'terms' から、本文の id を返す。知らないものは null */
export function legalDocId(urlOrId: string): string | null {
  const id = urlOrId.replace(/^\/legal\//, '')
  const resolved = ALIASES[id] ?? id
  return LEGAL_DOCS[resolved] ? resolved : null
}
