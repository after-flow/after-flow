/**
 * 「AIに相談」の入力欄に、手続きの画面からあらかじめ書いておく文。
 * 何についての質問かを先に入れておき、利用者は続きを書き足すだけで済むようにする。
 *
 * 手続きの名前は「死亡届を提出する」のような言い切りの形なので、そのまま「〜について」を続けると文が崩れる。
 * かぎかっこで囲んで、どの手続きのことかをはっきりさせる。
 * 末尾で改行し、利用者の質問は次の行から書きはじめられるようにする。
 */
export function taskChatDraft(title: string): string {
  return `「${title}」について。\n`
}
